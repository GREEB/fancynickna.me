function dedupe(arr: string[]): string[] {
	return Array.from(new Set(arr.filter((c) => c && c !== '')));
}

const cache = new Map<string, string[]>();

export function lookalikesFor(ch: string): string[] {
	if (!ch) return [];
	const key = ch.toLowerCase();
	if (cache.has(key)) return cache.get(key)!;

	const collected: string[] = [ch];

	// Pull every style's transformation of this character
	for (const s of styles) {
		try {
			const out = s.fn(ch);
			if (out && out !== ch) collected.push(out);
			// Also try uppercase, since some styles only map upper
			if (ch !== ch.toUpperCase()) {
				const upOut = s.fn(ch.toUpperCase());
				if (upOut && upOut !== ch.toUpperCase()) collected.push(upOut);
			}
		} catch {
			/* ignore broken transforms */
		}
	}

	// Manual homoglyph table
	if (manual[key]) collected.push(...manual[key]);

	const result = dedupe(collected);
	cache.set(key, result);
	return result;
}

